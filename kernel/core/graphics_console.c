static uint32_t cursor_column;
static uint32_t cursor_row;
static uint32_t columns;
static uint32_t rows;
static bool initialized;
static bool suspended;

static void fill_rectangle(uint32_t x, uint32_t y, uint32_t width,
                           uint32_t height, uint32_t color) {
        uint32_t *pixels = virtio_gpu_framebuffer();
        uint32_t stride = virtio_gpu_width();

        for (uint32_t row = y; row < y + height; row++) {
                for (uint32_t column = x; column < x + width; column++) {
                        pixels[(size_t)row * stride + column] = color;
                }
        }
}

static void draw_character_at(char character, uint32_t column, uint32_t row,
                              uint32_t foreground, uint32_t background) {
        uint32_t x = column * CELL_WIDTH;
        uint32_t y = row * CELL_HEIGHT;

        fill_rectangle(x, y, CELL_WIDTH, CELL_HEIGHT, background);
        if (character < ' ' || character > '~') {
                character = '?';
        }
        const uint8_t *glyph = font[(uint8_t)character - (uint8_t)' '];
        uint32_t *pixels = virtio_gpu_framebuffer();
        uint32_t stride = virtio_gpu_width();
        for (uint32_t glyph_x = 0U; glyph_x < GLYPH_WIDTH; glyph_x++) {
                for (uint32_t glyph_y = 0U; glyph_y < GLYPH_HEIGHT; glyph_y++) {
                        if ((glyph[glyph_x] & (1U << glyph_y)) == 0U) {
                                continue;
                        }
                        uint32_t pixel_x = x + 1U + glyph_x;
                        uint32_t pixel_y = y + 1U + glyph_y * 2U;
                        pixels[(size_t)pixel_y * stride + pixel_x] = foreground;
                        pixels[(size_t)(pixel_y + 1U) * stride + pixel_x] =
                            foreground;
                }
        }
}

static void draw_title(void) {
        static const char title[] = "ROSE  GRAPHICAL CONSOLE";

        fill_rectangle(0U, 0U, virtio_gpu_width(), TITLE_HEIGHT, COLOR_TITLE);
        for (size_t index = 0U; title[index] != '\0'; index++) {
                draw_character_at(title[index], (uint32_t)index + 2U, 0U,
                                  COLOR_TITLE_TEXT, COLOR_TITLE);
        }
}

static void scroll(void) {
        uint32_t *pixels = virtio_gpu_framebuffer();
        uint32_t width = virtio_gpu_width();
        uint32_t height = virtio_gpu_height();
        uint32_t start = TITLE_HEIGHT;

        for (uint32_t y = start; y + CELL_HEIGHT < height; y++) {
                for (uint32_t x = 0U; x < width; x++) {
                        pixels[(size_t)y * width + x] =
                            pixels[(size_t)(y + CELL_HEIGHT) * width + x];
                }
        }
        fill_rectangle(0U, height - CELL_HEIGHT, width, CELL_HEIGHT,
                       COLOR_BACKGROUND);
        (void)virtio_gpu_flush(0U, start, width, height - start);
}

void graphics_console_init(void) {
        if (!virtio_gpu_available()) {
                return;
        }

        columns = virtio_gpu_width() / CELL_WIDTH;
        rows = (virtio_gpu_height() - TITLE_HEIGHT) / CELL_HEIGHT;
        if (columns == 0U || rows == 0U) {
                return;
        }
        fill_rectangle(0U, 0U, virtio_gpu_width(), virtio_gpu_height(),
                       COLOR_BACKGROUND);
        draw_title();
        cursor_column = 0U;
        cursor_row = 0U;
        initialized = true;
        suspended = false;
        (void)virtio_gpu_flush(0U, 0U, virtio_gpu_width(), virtio_gpu_height());
}

bool graphics_console_available(void) { return initialized; }

void graphics_console_suspend(void) { suspended = true; }

void graphics_console_putc(char character) {
        if (!initialized || suspended) {
                return;
        }

        if (character == '\r') {
                cursor_column = 0U;
                return;
        }
        if (character == '\n') {
                cursor_column = 0U;
                cursor_row++;
        } else if (character == '\b' || character == 0x7f) {
                if (cursor_column != 0U) {
                        cursor_column--;
                        draw_character_at(' ', cursor_column, cursor_row + 2U,
                                          COLOR_FOREGROUND, COLOR_BACKGROUND);
                        (void)virtio_gpu_flush(cursor_column * CELL_WIDTH,
                                               TITLE_HEIGHT +
                                                   cursor_row * CELL_HEIGHT,
                                               CELL_WIDTH, CELL_HEIGHT);
                }
        } else if (character == '\t') {
                cursor_column = (cursor_column + 4U) & ~3U;
        } else if (character >= ' ') {
                draw_character_at(character, cursor_column, cursor_row + 2U,
                                  COLOR_FOREGROUND, COLOR_BACKGROUND);
                (void)virtio_gpu_flush(cursor_column * CELL_WIDTH,
                                       TITLE_HEIGHT + cursor_row * CELL_HEIGHT,
                                       CELL_WIDTH, CELL_HEIGHT);
                cursor_column++;
        }

        if (cursor_column >= columns) {
                cursor_column = 0U;
                cursor_row++;
        }
        if (cursor_row >= rows) {
                scroll();
                cursor_row = rows - 1U;
        }
}
